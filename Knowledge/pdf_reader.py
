
import os
import hashlib
import logging
from pathlib import Path
from pypdf import PdfReader

BASE_DIR = Path(__file__).parent
PDF_DIR = BASE_DIR / "pdf_library"
OUTPUT_DIR = BASE_DIR / "extracted"

PDF_DIR.mkdir(parents=True, exist_ok=True)
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

CHUNK_SIZE = 1800
CHUNK_OVERLAP = 250

def calculate_file_hash(file_path):
    digest = hashlib.sha256()
    with open(file_path, "rb") as file:
        for block in iter(lambda: file.read(65536), b""):
            digest.update(block)
    return digest.hexdigest()

def extract_pdf(file_path):
    file_path = Path(file_path)
    if not file_path.exists() or file_path.suffix.lower() != ".pdf":
        raise ValueError("Invalid PDF file")

    reader = PdfReader(str(file_path))
    pages = []
    scanned_pages = []

    for page_number, page in enumerate(reader.pages, start=1):
        text = page.extract_text() or ""
        text = " ".join(text.split())

        if len(text) < 30:
            scanned_pages.append(page_number)

        pages.append({
            "page": page_number,
            "text": text
        })

    return {
        "filename": file_path.name,
        "file_hash": calculate_file_hash(file_path),
        "total_pages": len(reader.pages),
        "scanned_pages": scanned_pages,
        "pages": pages
    }

def split_text(text, chunk_size=CHUNK_SIZE, overlap=CHUNK_OVERLAP):
    text = text.strip()
    chunks = []
    start = 0

    while start < len(text):
        end = min(start + chunk_size, len(text))
        chunks.append(text[start:end])

        if end >= len(text):
            break

        start = end - overlap

    return chunks

def build_chunks(pdf_data):
    chunks = []

    for page in pdf_data["pages"]:
        page_chunks = split_text(page["text"])

        for index, content in enumerate(page_chunks):
            if content.strip():
                chunks.append({
                    "document": pdf_data["filename"],
                    "file_hash": pdf_data["file_hash"],
                    "page": page["page"],
                    "chunk": index,
                    "content": content
                })

    return chunks

def process_pdf(file_path):
    pdf_data = extract_pdf(file_path)
    chunks = build_chunks(pdf_data)

    result = {
        "filename": pdf_data["filename"],
        "file_hash": pdf_data["file_hash"],
        "total_pages": pdf_data["total_pages"],
        "scanned_pages": pdf_data["scanned_pages"],
        "total_chunks": len(chunks),
        "chunks": chunks
    }

    output_file = OUTPUT_DIR / (pdf_data["file_hash"] + ".json")

    import json

    with open(output_file, "w", encoding="utf-8") as file:
        json.dump(result, file, ensure_ascii=False, indent=2)

    return {
        "filename": pdf_data["filename"],
        "pages": pdf_data["total_pages"],
        "chunks": len(chunks),
        "scanned_pages": pdf_data["scanned_pages"],
        "file_hash": pdf_data["file_hash"],
        "output": str(output_file)
    }
